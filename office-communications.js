function dept(){ return departments.find(d=>d.id===selected) || departments[0]; }
function save(){ localStorage.setItem(key, JSON.stringify(history.slice(-100))); }
function addMessage(sender,text,type="staff",name=""){
  history.push({sender,text,type,name,at:new Date().toISOString()}); save(); renderLog();
}
function renderLog(){
  logEl.innerHTML = "";
  const visible = history.slice(-35);
  if (!visible.length) {
    const empty=document.createElement("div"); empty.className="office-msg system";
    empty.textContent="Belum ada percakapan. Pilih divisi lalu mulai berdiskusi.";
    logEl.appendChild(empty); return;
  }
  visible.forEach(m=>{
    const wrap=document.createElement("div"); wrap.className="office-msg "+m.type;
    if(m.type!=="system"){const meta=document.createElement("div");meta.className="office-chatmeta";meta.textContent=m.sender;wrap.appendChild(meta);}
    const body=document.createElement("div");body.textContent=m.text;wrap.appendChild(body);logEl.appendChild(wrap);
  });
  logEl.scrollTop=logEl.scrollHeight;
}
function renderStaff(){
  staffEl.innerHTML="";
  departments.forEach(d=>{
    const b=document.createElement("button");b.type="button";b.className=d.id===selected?"active":"";
    b.innerHTML='<span class="initial">'+d.initials+'</span><span><b>'+d.name+'</b><small>'+d.role+'</small></span>';
    b.addEventListener("click",()=>{selected=d.id;document.querySelector("#dept").value=d.id;renderStaff();addMessage("Sistem","Percakapan diarahkan ke "+d.name+".","system");});
    staffEl.appendChild(b);
  });
}
function detectDepartment(text){
  const q=text.toLowerCase();
  if(/bug|uji|test|error|gagal|audit|periksa|cek/.test(q))return "qa";
  if(/3d|model|karakter|ruangan|visual|animasi|tekstur/.test(q))return "art3d";
  if(/fps|lambat|performa|memory|memori|lag/.test(q))return "perf";
  if(/rilis|publish|deploy|build/.test(q))return "release";
  if(/kode|sistem|program|database|fitur|save|programming/.test(q))return "dev";
  return "design";
}
function responseFor(d,text){
  const q=text.toLowerCase();
  if(/halo|hai|hello|pagi|siang|sore|malam/.test(q))return "Halo, Founder. Saya siap membahas pekerjaan di bidang "+d.role.toLowerCase()+". Apa target yang ingin kita capai?";
  if(d.id==="design")return "Dari sisi Game Design, kita perlu menetapkan tujuan pemain, alur gameplay, aturan fitur, dan kriteria keberhasilan. Saya sarankan instruksi ini dipecah menjadi tujuan, prioritas, dan kondisi selesai. Apakah fokusnya pengalaman pemain atau keseimbangan gameplay?";
  if(d.id==="art3d")return "Dari sisi 3D Development, pekerjaan perlu dibagi menjadi aset, material, pencahayaan, animasi, dan optimasi scene. Kita perlu memastikan referensi visual dan target perangkat sebelum mulai membuat aset.";
  if(d.id==="dev")return "Dari sisi Programming, saya akan memetakan kebutuhan menjadi komponen, alur data, validasi, dan pengujian. Sebelum implementasi, kita perlu memastikan perilaku yang diharapkan dan bagian proyek yang boleh diubah.";
  if(d.id==="qa")return "Dari sisi QA, kita perlu langkah reproduksi, hasil yang diharapkan, hasil aktual, tingkat dampak, dan bukti pengujian. Saya sarankan pekerjaan ini dicatat sebagai tiket agar bisa dilacak sampai verifikasi ulang.";
  if(d.id==="perf")return "Dari sisi Performance Engineering, kita perlu mengukur kondisi awal terlebih dahulu: FPS, waktu muat, penggunaan memori, dan perangkat uji. Setelah itu baru kita tentukan optimasi berdasarkan hasil pengukuran.";
  return "Dari sisi Release Management, kita perlu memastikan branch tujuan, hasil pemeriksaan QA, catatan perubahan, dan persetujuan Founder. Tidak ada perubahan yang akan dipublikasikan otomatis dari prototipe ini.";
}
function sendMessage(){
  const text=input.value.trim(); if(!text)return;
  const d=dept();
  addMessage("Founder",text,"founder");
  addMessage(d.name,responseFor(d,text),"staff");
  input.value="";
}
function startMeeting(){
  const topic=input.value.trim();
  if(!topic){input.focus();return;}
  addMessage("Founder","Agenda rapat: "+topic,"founder");
  addMessage("Project coordination","Rapat singkat dimulai. Setiap divisi menyampaikan sudut pandang awal berdasarkan bidangnya.","system");
  departments.forEach(d=>{
    const answer=d.id==="design"?"Saya akan menilai dampak terhadap gameplay dan pengalaman pemain.":d.id==="art3d"?"Saya akan mengidentifikasi kebutuhan aset, scene, dan animasi.":d.id==="dev"?"Saya akan memetakan perubahan kode dan dependensinya.":d.id==="qa"?"Saya akan menyusun skenario uji dan kriteria penerimaan.":d.id==="perf"?"Saya akan menentukan metrik performa yang perlu diukur.":"Saya akan menyiapkan pemeriksaan branch, build, dan persetujuan rilis.";
    addMessage(d.name,answer,"staff");
  });
  input.value="";
}
